from pathlib import Path
import re
import json
import sys

root = Path(__file__).resolve().parents[1]
if len(sys.argv) != 2:
    raise SystemExit('用法：python scripts/import-brave-new-world.py <原书TXT路径>')
lines = Path(sys.argv[1]).read_text(encoding='utf-8-sig').splitlines()
heading = re.compile(r'^第[一二三四五六七八九十]+章$')
starts = [i for i, line in enumerate(lines) if heading.fullmatch(line.strip())]
assert len(starts) == 30, f'章节数量异常：{len(starts)}'
assert lines[starts[0]].strip() == '第一章' and lines[starts[18]].strip() == '第一章'
prefaces = [i for i, line in enumerate(lines) if line.strip() == '《重返美丽新世界》作者序']
assert len(prefaces) == 1 and starts[17] < prefaces[0] < starts[18]
out = root / 'docs/library/volume-95'
out.mkdir(parents=True, exist_ok=True)
pages = []
characters = 0
for index, start in enumerate(starts):
    end = starts[index + 1] if index + 1 < len(starts) else len(lines)
    if index == 17:
        end = prefaces[0]
    segment = lines[start + 1:end]
    markers = [i for i, line in enumerate(segment) if line.strip() == '* * *']
    assert len(markers) <= 1, f'第 {index + 1} 页注释分隔符异常'
    if markers:
        notes = [line.strip() for line in segment[markers[0] + 1:] if line.strip()]
        assert notes and all(re.match(r'^\[\d+\]', note) for note in notes), f'第 {index + 1} 页注释区异常'
        segment = segment[:markers[0]]
    content = [line.strip() for line in segment if line.strip()]
    assert content and all(not re.match(r'^\[\d+\]', line) for line in content)
    chapter = lines[start].strip()
    subtitle = content.pop(0) if index >= 18 else ''
    assert index < 18 or len(subtitle) < 30
    title = f'{chapter}　{subtitle}' if subtitle else chapter
    body = [re.sub(r'\[\d+\]', '', line) for line in content]
    assert not any(re.search(r'\[\d+\]', line) for line in body)
    assert all(not any(char in line for char in ('<', '>', '{{', '}}', '`', '\\')) for line in body)
    characters += sum(len(line) for line in body)
    link = f'/library/volume-95/chapter-{index + 1:03d}'
    description = ('重返美丽新世界' if index >= 18 else '美丽新世界') + ' · ' + title
    markdown = '\n'.join(['---', f'title: {json.dumps(title, ensure_ascii=False)}', f'description: {json.dumps(description, ensure_ascii=False)}', '---', '', '<p class="reading-meta"><a href="/library/volume-95/">美丽新世界</a></p>', '', '# ' + title, '', '\n\n'.join(body), ''])
    (out / f'chapter-{index + 1:03d}.md').write_text(markdown, encoding='utf-8', newline='\n')
    pages.append({'text': title, 'link': link})
index_lines = ['---', 'title: "美丽新世界"', 'description: "奥尔德斯·赫胥黎作品，陈超译"', '---', '', '# 美丽新世界', '', '〔英〕奥尔德斯·赫胥黎 著，陈超 译。', '', '[开始阅读 →](/library/volume-95/chapter-001)', '', '## 目录', '', '### 美丽新世界', '']
index_lines += [f'- [{p["text"]}]({p["link"]})' for p in pages[:18]]
index_lines += ['', '### 附录：重返美丽新世界', '']
index_lines += [f'- [{p["text"]}]({p["link"]})' for p in pages[18:]]
(out / 'index.md').write_text('\n'.join(index_lines) + '\n', encoding='utf-8', newline='\n')
sidebar = [{'text': '美丽新世界', 'collapsed': True, 'items': [{'text': '本卷首页', 'link': '/library/volume-95/'}, {'text': '美丽新世界', 'collapsed': True, 'items': pages[:18]}, {'text': '附录：重返美丽新世界', 'collapsed': True, 'items': pages[18:]}]}]
catalog = [{'title': '美丽新世界', 'fullTitle': '美丽新世界（附重返美丽新世界）', 'volumeLabel': '新增卷', 'author': '〔英〕奥尔德斯·赫胥黎', 'link': '/library/volume-95/', 'firstPage': pages[0]['link'], 'pageCount': len(pages)}]
stats = {'volumeCount': 1, 'pageCount': len(pages), 'characterCount': characters}
module = '// Generated by scripts/import-brave-new-world.py.\n'
for name, value in [('braveNewWorldLibrarySidebar', sidebar), ('braveNewWorldLibraryCatalog', catalog), ('braveNewWorldLibraryStats', stats)]:
    module += 'export const ' + name + ' = ' + json.dumps(value, ensure_ascii=False, indent=2) + '\n\n'
(root / 'docs/.vitepress/library.brave-new-world.mjs').write_text(module, encoding='utf-8', newline='\n')
print(f'已整理 {len(pages)} 章，正文 {characters} 字符。')
